def _any(flags: str, *alternatives: str) -> str:
    """A pattern written one alternative per line: `flags` then `a|b|c`."""
    return flags + "|".join(alternatives)


def _group(before: str, after: str, *alternatives: str) -> str:
    """One alternative that is itself a group: `before(a|b|c)after`."""
    return f"{before}({'|'.join(alternatives)}){after}"


